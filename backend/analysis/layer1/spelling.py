def dictionary_path() -> Path | None:
    setting = os.environ.get("ANALYSIS_SPELL_DIC", "").strip()
    if setting.lower() in ("off", "none", "0", "false"):
        return None
    candidates = [Path(setting).expanduser()] if setting else list(DICTIONARY_LOCATIONS)
    for path in candidates:
        path = path.with_suffix(".dic") if path.suffix != ".dic" else path
        if path.exists() and path.with_suffix(".aff").exists():
            return path
    return None


@lru_cache(maxsize=4)
def _load_hunspell(path: str):
    try:
        from spylls.hunspell import Dictionary
    except ImportError:
        return None
    return Dictionary.from_files(str(Path(path).with_suffix("")))


def load_hunspell():
    """The German hunspell dictionary, or None when spylls or the dictionary is not installed."""
    path = dictionary_path()
    return _load_hunspell(str(path)) if path else None


# ---------------------------------------------------------------- checker


@dataclass
class Suggestion:
    word: str
    candidate: str
    distance: int
    alternatives: list[str] = field(default_factory=list)


class SpellChecker:
    def __init__(self, lexicon: dict[str, int] | None = None, hunspell=None, *, use_hunspell: bool = True):
        self.lexicon = load_lexicon() if lexicon is None else lexicon
        self.index = lexicon_index() if lexicon is None else build_index(
            w for w in self.lexicon if len(w) >= MIN_WORD_LENGTH - 1)
        self.hunspell = hunspell if hunspell is not None else (load_hunspell() if use_hunspell else None)
        self._known: dict[str, bool] = {}

    @property
    def dictionary_name(self) -> str | None:
        return "hunspell de_DE" if self.hunspell is not None else None

    def known(self, word: str) -> bool:
        if word not in self._known:
            self._known[word] = self._is_known(word)
        return self._known[word]

    def _is_known(self, word: str) -> bool:
        lower = word.lower()
        if lower in self.lexicon:
            return True
        if self.hunspell is not None:
            for form in {word, word[:1].upper() + word[1:], lower}:
                if self.hunspell.lookup(form):
                    return True
        return self._compound(lower, 0)

    def _compound(self, word: str, depth: int) -> bool:
        """Split into known lexicon parts, with optional linking letters ("Fugen-s")."""
        if depth > 2:
            return False
        for cut in range(MIN_PART_LENGTH, len(word) - MIN_PART_LENGTH + 1):
            head, rest = word[:cut], word[cut:]
            if head not in self.lexicon:
                continue
            for fuge in FUGEN:
                if not rest.startswith(fuge):
                    continue
                tail = rest[len(fuge):]
                if len(tail) >= MIN_PART_LENGTH and (tail in self.lexicon or self._compound(tail, depth + 1)):
                    return True
        return False

    def suggest(self, word: str, document_index: dict[str, list[str]] | None = None,
                weights: Counter | None = None) -> Suggestion | None:
        """The closest known word, if the word is unknown and the closest word is not just an inflection.

        Candidates come from the lexicon and from the document's own words (`document_index`, built with
        `build_index`); a document word only counts when it is known itself. The dictionary is asked last,
        and only for words that have a close neighbour, because each lookup costs a few milliseconds.
        """
        lower = word.lower()
        if lower in self.lexicon:
            return None
        limit = max_distance(lower)
        found: dict[str, int] = {}
        for index, from_document in ((self.index, False), (document_index or {}, True)):
            for variant in deletes(lower) | {lower}:
                for candidate in index.get(variant, ()):
                    if candidate == lower or candidate in found:
                        continue
                    d = distance(lower, candidate, limit)
                    if (d > limit or is_inflection(lower, candidate) or is_cut(lower, candidate)
                            or variant_key(candidate) == variant_key(lower)):
                        continue
                    if from_document and not self.known(candidate):
                        continue
                    found[candidate] = d
        if not found or self.known(word):
            return None
        umlauts = with_umlauts(word)
        if umlauts != word and self.known(umlauts):
            return None  # "Graeben" is "Gräben" typed without umlauts, not a typo of "Graben"
        weights = weights or Counter()

        def rank(candidate: str) -> tuple:
            return (found[candidate], -self.lexicon.get(candidate, 0), -weights[candidate], candidate)

        ordered = sorted(found, key=rank)
        best = ordered[0]
        alternatives = [c for c in ordered[1:] if found[c] == found[best]]
        return Suggestion(word, match_case(word, best), found[best], [match_case(word, a) for a in alternatives])


_override: SpellChecker | None = None


def default_checker() -> SpellChecker:
    return _override if _override is not None else _cached_checker()


@lru_cache(maxsize=1)
def _cached_checker() -> SpellChecker:
    return SpellChecker()


def use_checker(checker: SpellChecker | None) -> None:
    """Replace the checker the rules use (tests); None goes back to the default one."""
    global _override
    _override = checker


def reset() -> None:
    """Forget cached dictionaries (after changing ANALYSIS_SPELL_DIC)."""
    _cached_checker.cache_clear()
