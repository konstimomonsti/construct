"""Spell checking for tender texts without an LLM.

A word is *known* when it is in the domain lexicon (words used in at least 3 tender projects, see
`build_lexicon.py`), when the German hunspell dictionary accepts it, or when it splits into known parts.
An unknown word is a typo candidate only if a known word lies at Damerau distance 1 (2 for words of
12+ letters) and the pair is not just a German inflection ("Fugenband" / "Fugenbandes").

The hunspell dictionary is optional. It is GPL, so it is never shipped: it is loaded from a local path,
`ANALYSIS_SPELL_DIC` (path to the .dic file, the .aff next to it), or from a few well-known install
locations. Set `ANALYSIS_SPELL_DIC=off` to run with the lexicon only. Needs the `spylls` package.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field
from functools import lru_cache
import os
from pathlib import Path
import re
from typing import Iterable, Iterator

LEXICON_PATH = Path(__file__).with_name("lexicon_de.txt")              # generated by build_lexicon.py
EXTRA_LEXICON_PATH = Path(__file__).with_name("lexicon_extra_de.txt")  # curated by hand
MIN_PROJECTS = 3        # a word must appear in this many projects to enter the lexicon
MIN_WORD_LENGTH = 6     # shorter words have too many neighbours to judge
LONG_WORD_LENGTH = 12   # from this length a distance of 2 is allowed
MIN_PART_LENGTH = 4     # compound parts

LETTERS = "A-Za-zÄÖÜäöüß"
# A word, optionally hyphenated ("Baustrom-Kabel"). Letters glued to digits or underscores ("DN15") are not words.
WORD = re.compile(rf"(?<![\w-])[{LETTERS}]+(?:-[{LETTERS}]+)*(?![\w])")
# Anonymisation placeholders such as [FIRMA_096] or [PROJEKT_004].
ANONYMISED = re.compile(r"\[[A-Z]+(?:_[A-Z]+)*_\d+\]")
# Product names follow these words; quoted text, URLs and e-mail addresses are skipped too.
PRODUCT_CONTEXT = re.compile(
    r"(?:\b(?:Fabrikat|Hersteller|Typ|Type|Produkt|Modell|Serie|Marke|Artikel|Bezeichnung)\b\s*[:.]?"
    r"|\bz\.\s?B\.)[^\n;]{0,60}",
    re.IGNORECASE,
)
QUOTED = re.compile(r"\"[^\"\n]{1,80}\"|„[^“\n]{1,80}“|»[^«\n]{1,80}«")
# Anchored at the start of a run of non-spaces, so long runs ("..........") stay linear.
LINKS = re.compile(r"(?<!\S)\S*@\S+|\bwww\.\S+|https?://\S+")
MASKS = (ANONYMISED, PRODUCT_CONTEXT, QUOTED, LINKS)
# A word broken at the line end: "Desin-" + newline + "fizierung". "Wand- und Deckenflächen" is not broken.
BROKEN_BEFORE = re.compile(rf"[{LETTERS}]-\s+$")
BROKEN_AFTER = re.compile(rf"-\s+([a-zäöüß][{LETTERS}]*)")
CONJUNCTIONS = {"und", "oder", "bzw", "sowie", "bis", "als", "u", "o", "noch", "wie"}

# German inflection endings: a pair that differs only in these is not a typo.
ENDINGS = {"", "e", "n", "s", "m", "r", "en", "es", "er", "em", "rn", "ern", "ns", "nen", "se", "sen", "t", "te", "ten",
           "st"}
FUGEN = ("s", "es", "n", "en", "")


def mask(text: str) -> str:
    """Blank out text that is not prose (product names, placeholders, links). Offsets are kept."""
    for pattern in MASKS:
        text = pattern.sub(lambda m: " " * len(m.group(0)), text)
    return text


@dataclass(frozen=True)
class Token:
    text: str
    start: int
    end: int
    before: str = ""  # the word right before, when only one space separates them ("st atischen")
    after: str = ""   # the word right after, when only one space separates them ("Bodenb elag")


def tokens(text: str) -> Iterator[Token]:
    """Words of a text that are worth checking: not masked, not ALLCAPS, not CamelCase, not abbreviations,
    not halves of a word broken at the line end ("Desin-\\nfizierung", "geson- derten")."""
    masked = mask(text)
    matches = list(WORD.finditer(masked))
    for i, match in enumerate(matches):
        word = match.group(0)
        previous = matches[i - 1] if i else None
        following = matches[i + 1] if i + 1 < len(matches) else None
        before = previous.group(0) if previous and masked[previous.end():match.start()] == " " else ""
        after_word = following.group(0) if following and masked[match.end():following.start()] == " " else ""
        after = masked[match.end():match.end() + 3]
        if word.isupper() or after[:1] in ("®", "™"):
            continue
        if word[:1].islower() and BROKEN_BEFORE.search(masked, max(0, match.start() - 4), match.start()):
            continue
        broken = BROKEN_AFTER.match(masked, match.end())
        if broken and broken.group(1).lower() not in CONJUNCTIONS:
            continue
        if after[:1] == "." and len(word) <= 8 and (after[1:2].islower() or after[1:2].isdigit() or after[1:2] == ","
                                                   or after[1:3].strip()[:1].islower()):
            continue  # "einschl. Zubehör", "Ausf.,": an abbreviation
        yield Token(word, match.start(), match.end(), before, after_word)


def parts(word: str) -> list[str]:
    return [part for part in word.split("-") if part]


def checkable(part: str) -> bool:
    return len(part) >= MIN_WORD_LENGTH and not part.isupper() and not any(c.isupper() for c in part[1:])


def variant_key(word: str) -> str:
    """Spellings of the same word: case, hyphens, ß/ss and c/k before t ("Sectionaltor") are ignored."""
    return word.lower().replace("-", "").replace("ß", "ss").replace("ct", "kt")


def is_cut(a: str, b: str) -> bool:
    """One word is the other with letters missing at the start or the end: a cut word or an abbreviation
    ("Bodenb elag", "SC-K assette", "WC-Trennw,"), not a typo."""
    a, b = a.lower(), b.lower()
    if len(a) == len(b):  # only the last letter differs: an abbreviation ("Verschiebew.") or an ending
        return a[:-1] == b[:-1]
    short, long = sorted((a, b), key=len)
    return long.startswith(short) or long.endswith(short)


UMLAUT_SPELLING = (("ae", "ä"), ("oe", "ö"), ("ue", "ü"), ("Ae", "Ä"), ("Oe", "Ö"), ("Ue", "Ü"))


def with_umlauts(word: str) -> str:
    for plain, umlaut in UMLAUT_SPELLING:
        word = word.replace(plain, umlaut)
    return word


def is_inflection(a: str, b: str) -> bool:
    a, b = a.lower(), b.lower()
    common = 0
    while common < min(len(a), len(b)) and a[common] == b[common]:
        common += 1
    return a[common:] in ENDINGS and b[common:] in ENDINGS


def distance(a: str, b: str, limit: int) -> int:
    """Optimal string alignment (Damerau) distance, or limit + 1 when it is larger than `limit`."""
    if abs(len(a) - len(b)) > limit:
        return limit + 1
    previous2: list[int] = []
    previous = list(range(len(b) + 1))
    for i in range(1, len(a) + 1):
        current = [i] + [0] * len(b)
        for j in range(1, len(b) + 1):
            cost = 0 if a[i - 1] == b[j - 1] else 1
            current[j] = min(previous[j] + 1, current[j - 1] + 1, previous[j - 1] + cost)
            if i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]:
                current[j] = min(current[j], previous2[j - 2] + 1)
        if min(current) > limit:
            return limit + 1
        previous2, previous = previous, current
    return previous[-1] if previous[-1] <= limit else limit + 1


def deletes(word: str) -> set[str]:
    return {word[:i] + word[i + 1:] for i in range(len(word))}


def max_distance(word: str) -> int:
    return 2 if len(word) >= LONG_WORD_LENGTH else 1


def match_case(template: str, word: str) -> str:
    if template[:1].isupper():
        return word[:1].upper() + word[1:]
    return word.lower()


# ---------------------------------------------------------------- lexicon and dictionary


@lru_cache(maxsize=1)
def load_lexicon(paths: tuple[Path, ...] = (LEXICON_PATH, EXTRA_LEXICON_PATH)) -> dict[str, int]:
    """Lower-case word -> number of projects it appears in (curated extra words count as MIN_PROJECTS)."""
    lexicon: dict[str, int] = {}
    for path in paths:
        if not path.exists():
            continue
        for row in path.read_text(encoding="utf-8").splitlines():
            row = row.strip()
            if not row or row.startswith("#"):
                continue
            word, _, count = row.partition("\t")
            lexicon[word.lower()] = max(lexicon.get(word.lower(), 0), int(count or MIN_PROJECTS))
    return lexicon


@lru_cache(maxsize=1)
def lexicon_index() -> dict[str, list[str]]:
    """Delete-one index of the lexicon (SymSpell): variant -> lexicon words it comes from."""
    return build_index(word for word in load_lexicon() if len(word) >= MIN_WORD_LENGTH - 1)


def build_index(words: Iterable[str]) -> dict[str, list[str]]:
    index: dict[str, list[str]] = {}
    for word in words:
        for variant in deletes(word) | {word}:
            index.setdefault(variant, []).append(word)
    return index


